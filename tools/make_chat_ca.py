"""Export the unchanged ESP-IDF 5.5.3 Mozilla root set as full DER anchors.

Full anchors let Mbed TLS build cross-signed paths through its standard CA
callback, without depending on newer esp_crt_bundle Kconfig options.
"""
from pathlib import Path
import argparse
import hashlib
from cryptography import x509
from cryptography.hazmat.primitives.serialization import Encoding

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/certificates/esp-idf-5.5.3/cacrt_all.pem'
DEST = ROOT / 'main/generated/chat_ca'

def roots():
    return [(c.subject.public_bytes(), c.public_bytes(Encoding.DER))
            for c in x509.load_pem_x509_certificates(SOURCE.read_bytes())]

def generate(check=False):
    entries = roots()
    header = ('/* Generated by tools/make_chat_ca.py. */\n#pragma once\n'
              '#include <stddef.h>\n#include <stdint.h>\n'
              'typedef struct { const uint8_t *subject, *der; size_t subject_len, der_len; } chat_ca_t;\n'
              f'#define CHAT_CA_COUNT {len(entries)}U\n'
              'extern const chat_ca_t chat_ca_roots[CHAT_CA_COUNT];\n')
    source = ['/* Generated from the unchanged ESP-IDF 5.5.3 Mozilla CA set. */', '#include "chat_ca.h"']
    for i, (subject, der) in enumerate(entries):
        for label, data in [('subject', subject), ('der', der)]:
            source.append(f'static const uint8_t ca_{i}_{label}[] = {{')
            source += [','.join(f'0x{x:02x}' for x in data[j:j+24])+',' for j in range(0, len(data), 24)]
            source.append('};')
    source.append('const chat_ca_t chat_ca_roots[CHAT_CA_COUNT] = {')
    source += [f'{{ca_{i}_subject,ca_{i}_der,{len(s)}U,{len(d)}U}},' for i,(s,d) in enumerate(entries)]
    source += ['};', '']
    outputs = {'chat_ca.h': header, 'chat_ca.c': '\n'.join(source)}
    if not check: DEST.mkdir(parents=True, exist_ok=True)
    for name, text in outputs.items():
        path = DEST / name
        if check:
            if not path.exists() or path.read_text() != text: raise ValueError(f'Stale {path}')
        else: path.write_text(text,encoding='utf-8',newline='\n')
    print(f'{len(entries)} unchanged trust anchors; source SHA256={hashlib.sha256(SOURCE.read_bytes()).hexdigest()}')

if __name__ == '__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true')
    generate(p.parse_args().check)
