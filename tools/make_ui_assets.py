#!/usr/bin/env python3
"""Generate the Stelle companion's pixel fonts, icon fonts and room images.

Outputs (all deterministic, regenerated from the sources in tools/ui_assets):
  main/generated/ui/ui_assets.c / ui_assets.h  - LVGL 9 1-bpp fonts + RGB565 rooms
  assets/images/stelle-companion/qa/*.png      - nearest-neighbour previews

Fonts are 1 bpp so LVGL renders them without anti-aliasing. Larger sizes are
integer (nearest-neighbour) scale-ups of the same hand-drawn glyphs.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from ui_assets.glyphs import CAP_ROWS, GLYPHS  # noqa: E402
from ui_assets.fonts_extra import BIG, BIG_CAP, MEDIUM, MEDIUM_CAP, TINY, TINY_CAP  # noqa: E402
from ui_assets.icons import ICON_ORDER, ICONS  # noqa: E402
from ui_assets import rooms  # noqa: E402

ROOT = HERE.parent
OUT_C = ROOT / "main/generated/ui"
OUT_QA = ROOT / "assets/images/stelle-companion/qa"
ICON_BASE = 0xE000

# name, glyph set, cap rows, scale, bold, top padding rows, bottom padding rows
TEXT_FONTS = [
    ("ui_font_body", GLYPHS, CAP_ROWS, 1, False, 1, 1),     # cap 7: hints, nav labels
    ("ui_font_bold", GLYPHS, CAP_ROWS, 1, True, 1, 1),      # cap 7 bold: emphasis lines
    ("ui_font_medium", MEDIUM, MEDIUM_CAP, 1, False, 1, 1), # cap 9: list items, battery, values
    ("ui_font_speech", MEDIUM, MEDIUM_CAP, 1, True, 1, 1),  # cap 9 bold: the speech bubble
    ("ui_font_title", TINY, TINY_CAP, 2, False, 0, 0),      # cap 10, 2 px strokes: titles
    ("ui_font_digits", BIG, BIG_CAP, 2, False, 0, 0),       # 18 x 22, 4 px strokes: clock
]
ICON_FONTS = [("ui_icons_1x", 1), ("ui_icons_2x", 2), ("ui_icons_3x", 3)]


def ink_rows(rows, bold):
    w = len(rows[0]) + (1 if bold else 0)
    out = []
    for row in rows:
        bits = [False] * w
        for x, ch in enumerate(row):
            if ch == "#":
                bits[x] = True
                if bold:
                    bits[x + 1] = True
        out.append(bits)
    return out


def pack_bits(grid):
    bits = [b for row in grid for b in row]
    data = bytearray()
    for i in range(0, len(bits), 8):
        byte = 0
        for j, b in enumerate(bits[i:i + 8]):
            if b:
                byte |= 0x80 >> j
        data.append(byte)
    return bytes(data)


def scaled_box(grid, scale):
    """Crop to ink, then integer-scale. Returns (bitmap_grid, x0, y0, y1) in unscaled rows."""
    ys = [y for y, row in enumerate(grid) if any(row)]
    if not ys:
        return None
    xs = [x for row in grid for x, b in enumerate(row) if b]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    crop = [row[x0:x1 + 1] for row in grid[y0:y1 + 1]]
    big = []
    for row in crop:
        line = [b for b in row for _ in range(scale)]
        big.extend([line] * scale)
    return big, x0, y0, y1


class FontWriter:
    def __init__(self, name):
        self.name = name
        self.bitmap = bytearray()
        self.dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
        self.metrics = {}

    def add(self, code, big, adv, ofs_x, ofs_y, width_px):
        index = len(self.bitmap)
        if big is None:
            self.bitmap.append(0)
            box_w = box_h = 0
        else:
            self.bitmap.extend(pack_bits(big))
            box_w, box_h = len(big[0]), len(big)
        self.dsc.append(
            f"    {{.bitmap_index = {index}, .adv_w = {adv * 16}, .box_w = {box_w}, .box_h = {box_h}, "
            f".ofs_x = {ofs_x}, .ofs_y = {ofs_y}}} /* U+{code:04X} */")
        self.metrics[code] = adv
        assert box_w < 256 and box_h < 256 and -128 <= ofs_y < 128 and index < (1 << 20)

    def emit(self, ranges, line_height, base_line):
        n = self.name
        c = [f"/* {n}: generated by tools/make_ui_assets.py, 1 bpp, no anti-aliasing. */",
             f"static const uint8_t {n}_bitmap[] = {{"]
        for i in range(0, len(self.bitmap), 20):
            c.append("    " + ",".join(f"0x{b:02x}" for b in self.bitmap[i:i + 20]) + ",")
        c += ["};", f"static const lv_font_fmt_txt_glyph_dsc_t {n}_glyphs[] = {{", ",\n".join(self.dsc), "};",
              f"static const lv_font_fmt_txt_cmap_t {n}_cmaps[] = {{"]
        for start, length, first_id in ranges:
            c.append(f"    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {first_id}, "
                     ".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                     ".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
        c += ["};",
              f"static const lv_font_fmt_txt_dsc_t {n}_dsc = {{",
              f"    .glyph_bitmap = {n}_bitmap, .glyph_dsc = {n}_glyphs, .cmaps = {n}_cmaps,",
              f"    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = {len(ranges)}, .bpp = 1,",
              "    .kern_classes = 0, .bitmap_format = LV_FONT_FMT_TXT_PLAIN, .stride = 0,",
              "};",
              f"const lv_font_t {n} = {{",
              "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
              "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
              f"    .line_height = {line_height}, .base_line = {base_line},",
              "    .subpx = LV_FONT_SUBPX_NONE, .underline_position = 0, .underline_thickness = 0,",
              f"    .dsc = &{n}_dsc, .fallback = NULL,",
              "};", ""]
        return "\n".join(c)


def ranges_for(codes):
    ranges, first_id = [], 1
    for code in codes:
        if ranges and ranges[-1][0] + ranges[-1][1] == code:
            ranges[-1][1] += 1
        else:
            ranges.append([code, 1, first_id])
        first_id += 1
    return [tuple(r) for r in ranges]


def text_font(name, glyphs, cap, scale, bold, top, bottom):
    chars = sorted(glyphs, key=ord)
    fw = FontWriter(name)
    for ch in chars:
        grid = ink_rows(glyphs[ch], bold)
        width = len(grid[0])
        adv = (width + 1) * scale
        box = scaled_box(grid, scale)
        if box is None:
            fw.add(ord(ch), None, adv, 0, 0, width)
            continue
        big, x0, _y0, y1 = box
        fw.add(ord(ch), big, adv, x0 * scale, (cap - 1 - y1) * scale, width)
    total = max(len(g) for g in glyphs.values())
    line_height = (top + total + bottom) * scale
    base_line = (total - cap + bottom) * scale
    return fw.emit(ranges_for([ord(c) for c in chars]), line_height, base_line), fw.metrics, line_height

def icon_font(name, scale):
    fw = FontWriter(name)
    line_h = max(len(ICONS[n]) for n in ICON_ORDER) * scale
    for i, icon in enumerate(ICON_ORDER):
        grid = [[ch == "#" for ch in row] for row in ICONS[icon]]
        big, x0, y0, y1 = scaled_box(grid, scale)
        h = len(grid) * scale
        top = (line_h - h) // 2 + y0 * scale
        ofs_y = line_h - top - len(big)
        fw.add(ICON_BASE + i, big, (len(grid[0]) + 1) * scale, x0 * scale, ofs_y, len(grid[0]))
    return fw.emit([(ICON_BASE, len(ICON_ORDER), 1)], line_h, 0), line_h


def rgb565(img):
    out = bytearray()
    for r, g, b in zip(*[iter(img.convert("RGB").tobytes())] * 3):
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        out += v.to_bytes(2, "little")
    return bytes(out)


def room_c(name, img):
    data = rgb565(img)
    lines = [f"_Alignas(4) static const uint8_t {name}_data[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines += ["};", f"const lv_image_dsc_t {name} = {{",
              "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,",
              f"               .w = {img.width}, .h = {img.height}, .stride = {img.width * 2}}},",
              f"    .data_size = sizeof({name}_data), .data = {name}_data,", "};", ""]
    return "\n".join(lines), len(data)


def preview_text(glyphs, text, scale, bold):
    width = sum(len(glyphs[c][0]) + (1 if bold else 0) + 1 for c in text) * scale + 4
    rows = max(len(g) for g in glyphs.values())
    img = Image.new("RGB", (max(width, 8), rows * scale + 2), "#F3F3F4")
    x = 2
    for c in text:
        grid = ink_rows(glyphs[c], bold)
        for y, row in enumerate(grid):
            for gx, b in enumerate(row):
                if b:
                    for sy in range(scale):
                        for sx in range(scale):
                            img.putpixel((x + gx * scale + sx, 1 + y * scale + sy), (0x24, 0x26, 0x2C))
        x += (len(grid[0]) + 1) * scale
    return img


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    parts = ['/* Generated by tools/make_ui_assets.py. Do not edit. */', '#include "ui_assets.h"', ""]
    metrics = {}
    for spec in TEXT_FONTS:
        src, m, lh = text_font(*spec)
        parts.append(src)
        metrics[spec[0]] = {"line_height": lh, "advance": {chr(k): v for k, v in m.items()}}
    for name, scale in ICON_FONTS:
        src, lh = icon_font(name, scale)
        parts.append(src)
        metrics[name] = {"line_height": lh}
    room_bytes = 0
    images = {}
    # Room images are no longer compiled in: tools/make_asset_pack.py puts them
    # in the resource partition. They are still painted here for the QA sheet.
    for scene in rooms.SCENES:
        for phase in rooms.PHASES:
            images[(scene, phase)] = rooms.paint(phase, scene)
            room_bytes += rooms.W * rooms.H * 2

    header = ["/* Generated by tools/make_ui_assets.py. Do not edit. */", "#pragma once", '#include "lvgl.h"', ""]
    header += [f"extern const lv_font_t {spec[0]};" for spec in TEXT_FONTS]
    header += [f"extern const lv_font_t {name};" for name, _ in ICON_FONTS]
    header += [f"#define UI_ROOM_W {rooms.W}", f"#define UI_ROOM_H {rooms.H}"]
    for s in rooms.SCENES:  # rug centre in room pixels: where Stelle's ground shadow goes
        header += [f"#define UI_RUG_{s.upper()}_X {rooms.RUG[s][0]}", f"#define UI_RUG_{s.upper()}_Y {rooms.RUG[s][1]}"]
    header.append("")
    for i, icon in enumerate(ICON_ORDER):
        cp = ICON_BASE + i
        utf8 = chr(cp).encode("utf-8")
        header.append(f'#define UI_ICON_{icon.upper()} "' + "".join(f"\\x{b:02X}" for b in utf8) + '"')
    header.append("")

    files = {
        OUT_C / "ui_assets.c": "\n".join(parts),
        OUT_C / "ui_assets.h": "\n".join(header),
        OUT_C / "ui_metrics.json": json.dumps(metrics, indent=1, sort_keys=True) + "\n",
    }
    if args.check:
        stale = [str(p) for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("STALE: " + ", ".join(stale))
            return 1
        print("ui assets up to date")
        return 0

    OUT_C.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8", newline="\n")

    OUT_QA.mkdir(parents=True, exist_ok=True)
    sheet = Image.new("RGB", (rooms.W * 4 + 18, rooms.H * len(rooms.SCENES) + 6 * (len(rooms.SCENES) - 1)), "#24262C")
    for row, scene in enumerate(rooms.SCENES):
        for i, phase in enumerate(rooms.PHASES):
            images[(scene, phase)].save(OUT_QA / f"{scene}-{phase}.png")
            sheet.paste(images[(scene, phase)], (i * (rooms.W + 6), row * (rooms.H + 6)))
    sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(OUT_QA / "rooms-2x.png")
    sample = "STELLE 87% A quiet little moment. One small step. I'm with you. 0123456789 To-do Settings"
    spec_rows = [preview_text(GLYPHS, sample[:46], 2, False), preview_text(GLYPHS, sample[46:], 2, False),
                 preview_text(MEDIUM, "A quiet little moment. One small step. I'm with you.", 2, False),
                 preview_text(MEDIUM, "Take a breath. Mission complete! 87% Wave Jump Kick", 2, False),
                 preview_text(MEDIUM, "ABCDEFGHIJKLMNOPQRSTUVWXYZ 0123456789 abcdefghijklmnopqrstuvwxyz", 2, False),
                 preview_text(TINY, "STELLE TO-DO SETTINGS 80% WAVE", 4, False),
                 preview_text(BIG, "25:00 12:34", 2, False)]
    w = max(r.width for r in spec_rows)
    spec = Image.new("RGB", (w, sum(r.height for r in spec_rows)), "#F3F3F4")
    y = 0
    for r in spec_rows:
        spec.paste(r, (0, y))
        y += r.height
    spec.save(OUT_QA / "font-specimen.png")
    icon_w = sum(len(ICONS[n][0]) + 3 for n in ICON_ORDER)
    icons = Image.new("RGB", (icon_w, 19), "#E4E5E8")
    x = 1
    for n in ICON_ORDER:
        for yy, row in enumerate(ICONS[n]):
            for xx, ch in enumerate(row):
                if ch == "#":
                    icons.putpixel((x + xx, 1 + yy), (0x24, 0x26, 0x2C))
        x += len(ICONS[n][0]) + 3
    icons.resize((icons.width * 5, icons.height * 5), Image.NEAREST).save(OUT_QA / "icons-5x.png")
    print(json.dumps({"ok": True, "room_bytes": room_bytes, "glyphs": len(GLYPHS), "icons": len(ICON_ORDER)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
