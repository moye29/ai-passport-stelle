"""Preserve Enemy B sources and pack RGB565/alpha rows without full-frame RAM."""
from pathlib import Path
import argparse,json,hashlib,struct
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/images/stelle-companion/source/battle'
OUT=ROOT/'assets/images/stelle-companion/device/battle/enemy-b'
GEN=ROOT/'main/generated/battle'
W,H=216,146
NAMES=['1 - enemy B.png','2 - enemy B.png']

def pixels(image):
    rgba=image.tobytes()
    return [((((r>>3)<<11)|((g>>2)<<5)|(b>>3)) if a else 0,a) for r,g,b,a in zip(*[iter(rgba)]*4)]

def build(from_device=None):
    OUT.mkdir(parents=True,exist_ok=True);GEN.mkdir(parents=True,exist_ok=True)
    if from_device is None:
        previous=json.loads((OUT/'manifest.json').read_text()) if (OUT/'manifest.json').exists() else {}
        from_device=previous.get('origin')=='user_native_device'
    data=bytearray();rows=[];records=[]
    for name in NAMES:
        p=SOURCE/name
        with Image.open(OUT/name if from_device else p) as im:
            expected=(W,H) if from_device else (2160,1460)
            if im.size!=expected or im.mode!='RGBA':raise ValueError('invalid Enemy B canvas: '+name)
            image=im.copy() if from_device else im.resize((W,H),Image.Resampling.NEAREST)
        if not from_device:image.save(OUT/name)
        values=pixels(image)
        for y in range(H):
            rows.append(len(data));row=values[y*W:(y+1)*W];i=0
            while i<W:
                end=i+1
                if row[i][1]==0:
                    while end<W and end-i<64 and row[end][1]==0:end+=1
                    data.append(end-i-1)
                else:
                    while end<W and end-i<64 and row[end]==row[i]:end+=1
                    if end-i>=2:
                        data.append(128+end-i-1);data.extend(struct.pack('<HB',*row[i]))
                    else:
                        opaque=row[i][1]==255
                        while end<W and end-i<64 and row[end][1]!=0 and (row[end][1]==255)==opaque and not(end+1<W and row[end]==row[end+1]):end+=1
                        data.append((64 if opaque else 192)+end-i-1)
                        for color,a in row[i:end]:data.extend(struct.pack('<H',color) if opaque else struct.pack('<HB',color,a))
                i=end
        rows.append(len(data))
        records.append(dict(file=name,source_sha256=hashlib.sha256(p.read_bytes()).hexdigest(),
            device_sha256=hashlib.sha256((OUT/name).read_bytes()).hexdigest()))
    c=['/* Generated by tools/prepare_enemy_b.py. */','#include "enemy_b_pack.h"','static const uint8_t data[] = {']
    c.extend('    '+','.join(f'0x{v:02x}' for v in data[i:i+24])+',' for i in range(0,len(data),24))
    c.extend(['};','static const uint32_t rows[] = {'])
    c.extend('    '+','.join(str(v)+'U' for v in rows[i:i+12])+',' for i in range(0,len(rows),12))
    c.extend(['};','const enemy_b_art_pack_t enemy_b_art_pack={data,sizeof(data),rows,sizeof(rows)/sizeof(rows[0])};\n'])
    (GEN/'enemy_b_pack.h').write_text('/* Generated by tools/prepare_enemy_b.py. */\n#pragma once\n#include "enemy_b_art.h"\nextern const enemy_b_art_pack_t enemy_b_art_pack;\n',encoding='utf-8',newline='\n')
    (GEN/'enemy_b_pack.c').write_text('\n'.join(c),encoding='utf-8',newline='\n')
    m=dict(canvas=[W,H],origin='user_native_device' if from_device else 'prepared_large_source',
        format='2-bit packet kind + 6-bit count-minus-one: transparent/opaque/repeat RGBA/literal RGBA',
        rights='User supplied; redistribution rights unspecified',frames=records,storage_bytes=len(data)+4*len(rows),
        generated={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in GEN.glob('enemy_b_pack.*')})
    (OUT/'manifest.json').write_text(json.dumps(m,indent=2)+'\n');print(json.dumps(m))

def check(decoded):
    m=json.loads((OUT/'manifest.json').read_text());expected=bytearray()
    for e in m['frames']:
        assert hashlib.sha256((SOURCE/e['file']).read_bytes()).hexdigest()==e['source_sha256']
        assert hashlib.sha256((OUT/e['file']).read_bytes()).hexdigest()==e['device_sha256']
        native=m.get('origin')=='user_native_device'
        with Image.open(OUT/e['file'] if native else SOURCE/e['file']) as im:
            if native and (im.size!=(W,H) or im.mode!='RGBA'):raise ValueError('invalid native Enemy B canvas')
            want=im.copy() if native else im.resize((W,H),Image.Resampling.NEAREST)
        with Image.open(OUT/e['file']) as im:assert im.tobytes()==want.tobytes()
        values=pixels(want)
        for y in range(H):
            row=values[y*W:(y+1)*W]
            expected.extend(struct.pack('<'+str(W)+'H',*(p[0] for p in row)))
            expected.extend(p[1] for p in row)
    for n,h in m['generated'].items():assert hashlib.sha256((GEN/n).read_bytes()).hexdigest()==h
    if decoded:assert Path(decoded).read_bytes()==expected,'C decoder differs from RGB565/alpha source'
    print('Enemy B source positions, alpha and generated payload'+('/ C decode' if decoded else '')+': PASS')

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');ap.add_argument('--decoded')
    mode=ap.add_mutually_exclusive_group()
    mode.add_argument('--from-device',dest='from_device',action='store_true',help='pack user-edited native PNGs without writing them')
    mode.add_argument('--from-source',dest='from_device',action='store_false',help='explicitly regenerate native PNGs from large sources')
    ap.set_defaults(from_device=None)
    args=ap.parse_args();check(args.decoded) if args.check else build(args.from_device)
