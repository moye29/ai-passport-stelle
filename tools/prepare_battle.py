"""Prepare the approved Battle frames and hit cue, preserving all source files."""
import argparse, array, hashlib, json, struct, subprocess, sys, zlib
from pathlib import Path
from PIL import Image
from make_asset_pack import sprite_bytes, crop_frame
from prepare_anniv_bgm import encode

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/images/stelle-companion/source/battle'
DEVICE = ROOT / 'assets/images/stelle-companion/device/battle'
GENERATED = ROOT / 'main/generated/battle'
POSITION_UPDATED = {
    '0.png': '0 - position updated.png',
    '1.png': '1 - position updated.png',
    '2-1.png': '2 - position updated.png',
    '2-2.png': '0 - position updated.png',
}

def build(ffmpeg, hit_source=None, hit_pack=None):
    DEVICE.mkdir(parents=True, exist_ok=True)
    GENERATED.mkdir(parents=True, exist_ok=True)
    present=[(SOURCE/name).is_file() for name in set(POSITION_UPDATED.values())]
    if any(present) and not all(present): raise ValueError('position-updated Battle source set is incomplete')
    updated=all(present)
    records, data, descriptors, shared = [], bytearray(), [], {}
    for name in ['0.png', '1.png', '2-1.png', '2-2.png']:
        source_name=POSITION_UPDATED[name] if updated else name
        source = SOURCE/source_name
        with Image.open(source) as original:
            if original.size != (2160,1460) or original.mode != 'RGBA':
                raise ValueError('unexpected Battle source canvas: '+name)
            frame = original.resize((216,146), Image.Resampling.NEAREST)
        frame.save(DEVICE/name)
        crop, ox, oy = crop_frame(frame)
        raw = sprite_bytes(crop); key = (crop.size,raw)
        if key not in shared:
            data.extend(bytes((-len(data))%4)); shared[key]=len(data); data.extend(raw)
        descriptors.append((shared[key],len(raw),crop.width,crop.height,ox,oy))
        records.append(dict(source=source_name,device=name,sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                            device_sha256=hashlib.sha256((DEVICE/name).read_bytes()).hexdigest(),
                            crop=[ox,oy,crop.width,crop.height]))
    audio_source=Path(hit_pack or hit_source).resolve() if (hit_pack or hit_source) else SOURCE/'hit.mp3'
    audio_relative=audio_source.relative_to(ROOT).as_posix()
    if hit_pack:
        hit=audio_source.read_bytes()
        if len(hit)<32 or hit[:4]!=b'SBGM': raise ValueError('invalid selected hit pack')
        version,rate,blocks,block_size,crc=struct.unpack_from('<IIIII',hit,4)
        if (version,rate,block_size)!=(1,12000,124) or not blocks or len(hit)!=32+blocks*124 or zlib.crc32(hit[32:])!=crc:
            raise ValueError('invalid selected hit pack header/CRC')
        source_samples=blocks*240
    else:
        pcm=array.array('h', subprocess.check_output([ffmpeg,'-v','error','-i',str(audio_source),
            '-ar','12000','-ac','1','-f','s16le','-']))
        if sys.byteorder != 'little': pcm.byteswap()
        source_samples=len(pcm)
        if source_samples == 0: raise ValueError('empty hit cue')
        # Preserve the full original cue, with only 4ms edge ramps and final block padding.
        fade=min(48,len(pcm)//4)
        for i in range(fade):
            pcm[i]=int(pcm[i]*i/fade); pcm[-1-i]=int(pcm[-1-i]*i/fade)
        pcm.extend([0]*((-len(pcm))%240))
        hit,_=encode(pcm)
    (DEVICE/'hit.sbgm').write_bytes(hit)
    header='''/* Generated by tools/prepare_battle.py. */
#pragma once
#include "lvgl.h"
#include <stddef.h>
#include <stdint.h>
typedef struct { lv_image_dsc_t image; int16_t ox, oy; } battle_frame_t;
extern const battle_frame_t battle_frames[4];
extern const uint8_t battle_hit_data[];
extern const size_t battle_hit_size;
'''
    c=['/* Generated by tools/prepare_battle.py; pixels stay in Flash. */','#include "battle_pack.h"']
    for symbol,raw in [('battle_pixels',data),('battle_hit_data',hit)]:
        c.append(('static ' if symbol=='battle_pixels' else '')+'const uint8_t '+symbol+'[] = {')
        c.extend('    '+','.join(f'0x{b:02x}' for b in raw[i:i+24])+',' for i in range(0,len(raw),24))
        c.append('};')
    c.append('const size_t battle_hit_size = sizeof(battle_hit_data);')
    c.append('const battle_frame_t battle_frames[4] = {')
    for offset,size,w,h,ox,oy in descriptors:
        c.append(f'    {{.image={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565A8,.w={w},.h={h},.stride={w*2}}},.data_size={size},.data=battle_pixels+{offset}}},.ox={ox},.oy={oy}}},')
    c.append('};\n')
    (GENERATED/'battle_pack.h').write_text(header,encoding='utf-8',newline='\n')
    (GENERATED/'battle_pack.c').write_text('\n'.join(c),encoding='utf-8',newline='\n')
    manifest=dict(canvas=[216,146],source_rights='User supplied; redistribution rights unspecified',
        frames=records,unique_image_bytes=len(data),hit_bytes=len(hit),hit_seconds=source_samples/12000,
        hit_source_path=audio_relative,
        original_hit_sha256=hashlib.sha256((SOURCE/'hit.mp3').read_bytes()).hexdigest(),
        hit_source_sha256=hashlib.sha256(audio_source.read_bytes()).hexdigest(),
        hit_sha256=hashlib.sha256(hit).hexdigest(),
        generated={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in GENERATED.glob('battle_pack.*')})
    (DEVICE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(manifest))

def check():
    m=json.loads((DEVICE/'manifest.json').read_text())
    for entry in m['frames']:
        source=SOURCE/entry['source']; device=DEVICE/entry.get('device',entry['source'])
        assert hashlib.sha256(source.read_bytes()).hexdigest()==entry['sha256']
        assert hashlib.sha256(device.read_bytes()).hexdigest()==entry['device_sha256']
        with Image.open(source) as im: expected=im.resize((216,146),Image.Resampling.NEAREST)
        with Image.open(device) as im: assert im.tobytes()==expected.tobytes()
    audio_source=ROOT/m['hit_source_path'] if 'hit_source_path' in m else SOURCE/'hit.mp3'
    assert hashlib.sha256(audio_source.read_bytes()).hexdigest()==m['hit_source_sha256']
    if 'original_hit_sha256' in m:
        assert hashlib.sha256((SOURCE/'hit.mp3').read_bytes()).hexdigest()==m['original_hit_sha256']
    assert hashlib.sha256((DEVICE/'hit.sbgm').read_bytes()).hexdigest()==m['hit_sha256']
    for name,digest in m['generated'].items(): assert hashlib.sha256((GENERATED/name).read_bytes()).hexdigest()==digest
    print('Battle source hashes, exact canvas transform and generated payload: PASS')

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__); ap.add_argument('--ffmpeg'); ap.add_argument('--check',action='store_true')
    ap.add_argument('--hit-source', help='selected project audio file; preserves original hit.mp3')
    ap.add_argument('--hit-pack', help='selected prepared SBGM cue, used byte-for-byte without re-encoding')
    args=ap.parse_args()
    if args.check: check()
    elif args.ffmpeg or args.hit_pack: build(args.ffmpeg,args.hit_source,args.hit_pack)
    else: ap.error('--ffmpeg is required to prepare resources')
