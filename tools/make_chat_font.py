"""Generate a history-only 16 px GNU Unifont subset; existing UI fonts are untouched."""
from pathlib import Path
import gzip
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "assets/fonts/stelle-chat"
SOURCE = BASE / "unifont-16.0.04.hex.gz"
RANGES = ((0x20, 0x7E), (0x2000, 0x206F), (0x3000, 0x30FF), (0x4E00, 0x9FFF), (0xFF00, 0xFFEF), (0xFFFD, 0xFFFD))

def generate():
    glyphs = {}
    for line in gzip.decompress(SOURCE.read_bytes()).decode("ascii").splitlines():
        code, bits = line.split(":")
        glyphs[int(code, 16)] = bytes.fromhex(bits)
    output = ['/* Stelle Chat 16: GNU Unifont 16.0.04 subset, SIL OFL 1.1.',
              ' * Generated by tools/make_chat_font.py. See LICENSE.txt in this directory. */',
              '#include "lvgl.h"', 'static const uint8_t bitmap[] = {']
    bitmap = bytearray()
    records = ['{0}']
    maps = []
    missing = []
    gid = 1
    for start, end in RANGES:
        maps.append(f'{{.range_start={start},.range_length={end-start+1},.glyph_id_start={gid},.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}')
        for code in range(start, end+1):
            raw = glyphs.get(code)
            if raw is None:
                missing.append(code)
                raw = glyphs[0xFFFD]
            width = len(raw)//2
            records.append(f'{{.bitmap_index={len(bitmap)},.adv_w={width*16},.box_w={width},.box_h=16,.ofs_y=0}}')
            bitmap.extend(raw)
            gid += 1
    for i in range(0, len(bitmap), 24):
        output.append(','.join(f'0x{b:02x}' for b in bitmap[i:i+24])+',')
    output += ['};', 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {', ',\n'.join(records), '};',
               'static const lv_font_fmt_txt_cmap_t maps[] = {', ',\n'.join(maps), '};',
               'static const lv_font_fmt_txt_dsc_t descriptor = {',
               f'.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=maps,.cmap_num={len(maps)},.bpp=1,',
               '.bitmap_format=LV_FONT_FMT_TXT_PLAIN,.stride=0};',
               'const lv_font_t stelle_chat_font = {',
               '.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
               '.line_height=16,.base_line=0,.dsc=&descriptor};', '']
    (BASE/'stelle_chat_font.c').write_text('\n'.join(output), encoding='utf-8')
    report = dict(name='Stelle Chat 16', source='GNU Unifont 16.0.04', license='SIL OFL 1.1',
                  source_sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(), ranges=RANGES,
                  glyph_count=gid-1, bitmap_bytes=len(bitmap), missing=missing)
    (BASE/'coverage.json').write_text(json.dumps(report, indent=2)+'\n',encoding='utf-8')
    print(f'History font: {gid-1} glyphs, {len(bitmap)} bitmap bytes, {len(missing)} source gaps')

if __name__ == '__main__':
    generate()
