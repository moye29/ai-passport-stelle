def _widen(rows):
    """Insert one column: duplicate the interior column with the least ink."""
    w = len(rows[0])
    if w < 4:
        return rows
    cols = range(1, w - 1)
    centre = (w - 1) / 2
    best = min(cols, key=lambda c: (sum(r[c] == "#" for r in rows), abs(c - centre)))
    return [r[:best + 1] + r[best] + r[best + 1:] for r in rows]


