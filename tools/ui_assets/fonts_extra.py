def _derive_medium():
    out = {}
    for ch, rows in GLYPHS.items():
        if ch in _MEDIUM_OVERRIDES:
            out[ch] = _MEDIUM_OVERRIDES[ch]
            continue
        top = LOWER_MAP if ch.islower() else CAP_MAP
        body = [rows[i] for i in top] + rows[7:9]
        if ch.isalnum() and ch not in "Iil1":
            body = _widen(body)
        out[ch] = body
    for ch, rows in out.items():
        assert len(rows) == 11 and len({len(r) for r in rows}) == 1, ch
    return out


MEDIUM = _derive_medium()
