"""1-bit pixel icons. Each icon is a list of equal-length rows ('#' = ink).

Circular icons are rasterised from simple integer-grid rules so their pixel
edges stay hard; the rest are drawn by hand. The generator stores them in an
LVGL icon font addressed by Private Use code points.
"""
import math


def _grid(w, h, ink):
    return ["".join("#" if ink(x, y) else "." for x in range(w)) for y in range(h)]


def _ring(cx, cy, r0, r1):
    return lambda x, y: r0 <= math.hypot(x - cx, y - cy) <= r1


def _clock():
    ring = _ring(7, 7, 5.1, 7.2)
    hands = lambda x, y: (x in (7,) and 3 <= y <= 7) or (y == 7 and 7 <= x <= 10) or (x == 6 and 3 <= y <= 8) or (y == 8 and 6 <= x <= 10)
    return _grid(15, 15, lambda x, y: ring(x, y) or hands(x, y))


def _gear():
    def ink(x, y):
        dx, dy = x - 7, y - 7
        d = math.hypot(dx, dy)
        if d < 2.3:
            return False
        if d <= 5.0:
            return True
        a = (math.degrees(math.atan2(dy, dx)) + 360) % 45
        return d <= 7.3 and (a < 11.5 or a > 33.5)
    return _grid(15, 15, ink)


def _clock_n():
    ring = _ring(8, 8, 6.3, 8.4)
    hands = lambda x, y: (x in (7, 8) and 4 <= y <= 9) or (y in (8, 9) and 7 <= x <= 12)
    return _grid(17, 17, lambda x, y: ring(x, y) or hands(x, y))


def _gear_n():
    def ink(x, y):
        dx, dy = x - 8, y - 8
        d = math.hypot(dx, dy)
        if d < 2.6:
            return False
        if d <= 5.8:
            return True
        a = (math.degrees(math.atan2(dy, dx)) + 360) % 45
        return d <= 8.4 and (a < 12 or a > 33)
    return _grid(17, 17, ink)


def _sun():
    def ink(x, y):
        dx, dy = x - 7, y - 7
        d = math.hypot(dx, dy)
        if d <= 3.2:
            return True
        if dx == 0 or dy == 0:
            return 5 <= d <= 7
        if abs(dx) == abs(dy):
            return 3.9 <= d <= 6.0
        return False
    return _grid(15, 15, ink)


def _moon():
    outer = lambda x, y: math.hypot(x - 7, y - 7) <= 6.6
    bite = lambda x, y: math.hypot(x - 10.2, y - 4.6) <= 5.2
    rows = [list(r) for r in _grid(15, 15, lambda x, y: outer(x, y) and not bite(x, y))]
    # A tiny sparkle in the bitten corner.
    for x, y in ((12, 1), (11, 2), (12, 2), (13, 2), (12, 3)):
        rows[y][x] = "#"
    return ["".join(r) for r in rows]


