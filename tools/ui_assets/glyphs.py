def _parse():
    glyphs = {}
    for block in _RAW.split("\n@")[1:]:
        lines = block.split("\n")
        key = lines[0]
        rows = [line for line in lines[1:] if line]
        if key.startswith("\\u"):
            key = chr(int(key[2:], 16))
        elif key.strip() == "":
            key = " "  # the "@ " header may lose its trailing space
        if len(key) != 1:
            raise ValueError(f"bad glyph key {key!r}")
        if len(rows) == 7:
            rows += ["." * len(rows[0])] * 2
        if len(rows) != 9 or len({len(r) for r in rows}) != 1:
            raise ValueError(f"glyph {key!r} must be 7 or 9 equal rows")
        glyphs[key] = rows
    return glyphs


GLYPHS = _parse()
CAP_ROWS = 7      # rows 0..6 are above or on the baseline
TOTAL_ROWS = 9    # rows 7..8 are descenders
