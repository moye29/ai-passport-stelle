"""Pack eight anniversary images using one RGB565 palette/base plus row deltas."""
from pathlib import Path
import argparse,hashlib,json,struct
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/images/stelle-companion/device/anniversary'
OUT=SOURCE/'prepared'
GEN=ROOT/'main/generated/anniv'
W,H,N=216,136,8

def images():
    result=[]
    for i in range(N):
        p=SOURCE/f'anniv_{i}.png'
        with Image.open(p) as im:
            if im.size!=(W,H) or im.mode!='RGB': raise ValueError('expected native 216x136 RGB: '+p.name)
            values=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in im.getdata()]
        result.append(values)
    return result

def build():
    OUT.mkdir(parents=True,exist_ok=True);GEN.mkdir(parents=True,exist_ok=True)
    frames=images();palette=sorted(set(v for f in frames for v in f))
    if len(palette)>256: raise ValueError('lossless RGB565 shared palette needs more than 256 entries')
    index={v:i for i,v in enumerate(palette)}
    frames=[bytes(index[v] for v in f) for f in frames]
    base=frames[0];delta=bytearray();rows=[0]*(H+1)
    for f in frames[1:]:
        for y in range(H):
            rows.append(len(delta));at=y*W;end=at+W
            while at<end:
                same=f[at]==base[at];stop=at+1
                while stop<end and stop-at<128 and (f[stop]==base[stop])==same:stop+=1
                delta.append((stop-at-1)|(0 if same else 128))
                if not same:delta.extend(f[at:stop])
                at=stop
        rows.append(len(delta))
    assert len(rows)==N*(H+1)
    c=['/* Generated by tools/prepare_anniv_frames.py. RGB565-exact row delta pack. */','#include "anniv_pack.h"']
    for name,ctype,values,perline,fmt in [('palette','uint16_t',palette,12,'0x%04x'),
        ('base','uint8_t',base,24,'0x%02x'),('delta','uint8_t',delta,24,'0x%02x'),('rows','uint32_t',rows,12,'%dU')]:
        c.append(f'static const {ctype} {name}[] = {{')
        c.extend('    '+','.join(fmt%v for v in values[i:i+perline])+',' for i in range(0,len(values),perline))
        c.append('};')
    c.append('const anniv_art_pack_t anniv_art_pack = {palette,sizeof(palette)/sizeof(palette[0]),base,sizeof(base),delta,sizeof(delta),rows,sizeof(rows)/sizeof(rows[0])};\n')
    (GEN/'anniv_pack.h').write_text('/* Generated by tools/prepare_anniv_frames.py. */\n#pragma once\n#include "anniv_art.h"\nextern const anniv_art_pack_t anniv_art_pack;\n',encoding='utf-8',newline='\n')
    (GEN/'anniv_pack.c').write_text('\n'.join(c),encoding='utf-8',newline='\n')
    manifest=dict(canvas=[W,H],frame_ms=200,cycle_ms=1600,frame_count=N,palette_colors=len(palette),
        storage_bytes=len(palette)*2+len(base)+len(delta)+len(rows)*4,
        format='shared RGB565 palette; indexed base; 7-bit skip/literal delta runs per row',
        rights='User-provided images; redistribution rights unspecified',
        frames=[dict(file=f'anniv_{i}.png',sha256=hashlib.sha256((SOURCE/f'anniv_{i}.png').read_bytes()).hexdigest()) for i in range(N)],
        generated={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in GEN.glob('anniv_pack.*')})
    (OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest))

def check(decoded):
    m=json.loads((OUT/'manifest.json').read_text())
    for f in m['frames']: assert hashlib.sha256((SOURCE/f['file']).read_bytes()).hexdigest()==f['sha256']
    for name,digest in m['generated'].items(): assert hashlib.sha256((GEN/name).read_bytes()).hexdigest()==digest
    if decoded:
        expected=b''.join(struct.pack('<'+str(W*H)+'H',*v) for v in images())
        assert Path(decoded).read_bytes()==expected,'C decoder differs from original RGB565 pixels'
    print('Anniversary originals/generated data'+('/ all eight C-decoded RGB565 frames' if decoded else '')+': PASS')

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');ap.add_argument('--decoded')
    args=ap.parse_args();check(args.decoded) if args.check else build()
